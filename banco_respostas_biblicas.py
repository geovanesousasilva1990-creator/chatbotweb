def buscar_resposta(pergunta):
    """
    Busca a melhor resposta para uma pergunta no banco de dados.
    Retorna a resposta mais relevante ou None se não encontrar.
    """
    import unicodedata
    
    def normalizar(texto):
        """Remove acentos e converte para minúsculas"""
        texto = unicodedata.normalize("NFKD", texto.lower())
        return "".join(c for c in texto if not unicodedata.combining(c))
    
    pergunta_norm = normalizar(pergunta)
    
    # Busca por palavras-chave
    melhor_match = None
    max_pontos = 0
    
    for chave, dados in BANCO_RESPOSTAS.items():
        if chave == "default":
            continue
            
        palavras_chave = dados.get("palavras_chave", [])
        pontos = 0
        
        for palavra_chave in palavras_chave:
            palavra_norm = normalizar(palavra_chave)
            if palavra_norm in pergunta_norm:
                pontos += len(palavra_norm)  # Quanto mais longa a correspondência, maior a pontuação
        
        if pontos > max_pontos:
            max_pontos = pontos
            melhor_match = chave
    
    # Retorna a resposta ou a resposta padrão
    if melhor_match:
        return BANCO_RESPOSTAS[melhor_match]["resposta"]
    
    return BANCO_RESPOSTAS["default"]["resposta"]
